func compilerOptionStrictValue(options *core.CompilerOptions, value any) bool {
	if value, ok := value.(core.Tristate); ok {
		return options.GetStrictOptionValue(value)
	}
	return false
}

func watchOptionsEqual(left *core.WatchOptions, right *core.WatchOptions) bool {
	if left == right {
		return true
	}
	if left == nil || right == nil {
		return false
	}
	return intPointersEqual(left.Interval, right.Interval) &&
		left.FileKind == right.FileKind &&
		left.DirectoryKind == right.DirectoryKind &&
		left.FallbackPolling == right.FallbackPolling &&
		left.SyncWatchDir == right.SyncWatchDir &&
		slices.Equal(left.ExcludeDir, right.ExcludeDir) &&
		slices.Equal(left.ExcludeFiles, right.ExcludeFiles)
}

func projectReferencesEqual(left []*core.ProjectReference, right []*core.ProjectReference) bool {
	if len(left) != len(right) {
		return false
	}
	for i := range left {
		if left[i] == right[i] {
			continue
		}
		if left[i] == nil || right[i] == nil ||
			left[i].Path != right[i].Path ||
			left[i].OriginalPath != right[i].OriginalPath ||
			left[i].Circular != right[i].Circular {
			return false
		}
	}
	return true
}

func (p *ParsedOptions) Equals(other *ParsedOptions) bool {
	if p == other {
		return true
	}
	if p == nil || other == nil {
		return false
	}
	return p.CompilerOptions.Equals(other.CompilerOptions) &&
		watchOptionsEqual(p.WatchOptions, other.WatchOptions) &&
		p.TypeAcquisition.Equals(other.TypeAcquisition) &&
		slices.Equal(p.FileNames, other.FileNames) &&
		projectReferencesEqual(p.ProjectReferences, other.ProjectReferences) &&
		slices.EqualFunc(p.ContentMappers, other.ContentMappers, (*contentmapper.Mapper).Equals)
}
